function buildCopies(
  bookCode: string,
  total: number,
  available: number,
  shelf: string,
  priceMvr: number,
  activeLoanId?: string
): BookCopy[] {
  const copies: BookCopy[] = [];
  for (let i = 1; i <= total; i++) {
    const isAvailable = i <= available;
    const rackCode = shelf.split(' - ')[0] || 'Main Rack';
    copies.push({
      copyId: `${bookCode}-C${i}`,
      barcode: `${bookCode}-${String(i).padStart(2, '0')}`,
      accessionNumber: `ACC-2025-${bookCode.replace(/[^0-9]/g, '').slice(-3) || '100'}${String(i).padStart(2, '0')}`,
      rackLocation: `${rackCode} · Tier ${((i - 1) % 3) + 1}`,
      shelfLocation: shelf,
      condition: i === 1 ? 'Good' : 'New',
      acquisitionPriceMvr: priceMvr,
      status: isAvailable ? 'Available' : 'Checked Out',
      currentLoanId: !isAvailable && i === available + 1 ? activeLoanId : undefined,
      acquiredAt: '2025-01-15',
    });
  }
  return copies;
}

